import { TITLE_CATALOG } from './title-catalog.ts'

export type ForgeCatalogKind = 'equipment' | 'titles'
export type ForgeCatalogItem = {
  id: string
  name: string
  slot: string | null
  detail: Record<string, string | number | null>
}

const equipmentSlots = [
  ['armor', 'Верх'],
  ['pants', 'Поножи'],
  ['boots', 'Сапоги'],
  ['bracers', 'Наручи'],
] as const
const equipmentGrades = [
  ['none', 'Нет'],
  ['r8', 'р8'],
  ['r8r', 'р8р'],
  ['r8r2', 'р8р2'],
  ['r9r2', 'р9р2'],
  ['xx1', 'ХХ1'],
  ['xx2', 'ХХ2'],
  ['xx3rent', 'Аренда ХХ3'],
  ['xx3payment', 'Аренда ХХ3 (платёж)'],
  ['xx3', 'ХХ3'],
  ['ts1', 'ТС1'],
  ['ts2', 'ТС2'],
] as const
const equipment = equipmentSlots.flatMap(([slot, slotName]) =>
  equipmentGrades.map(([grade, gradeName]) => ({
    id: `equip-${slot}-${grade}`,
    name: `${slotName}: ${gradeName}`,
    slot,
    detail: { slot, grade },
  })),
)
const titles: ForgeCatalogItem[] = TITLE_CATALOG.map((row) => ({
  id: row.id,
  name: row.name,
  slot: null,
  detail: {
    titleName: row.titleName,
    itemId: row.itemId,
    level: row.level,
    stat: row.stat,
    medal: row.medal,
  },
}))

export const FORGE_CATALOGS: Readonly<
  Record<ForgeCatalogKind, readonly ForgeCatalogItem[]>
> = {
  equipment,
  titles,
}

